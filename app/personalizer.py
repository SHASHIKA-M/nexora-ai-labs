"""Personalisation of a materialised blueprint.

The AI employees' structured output (branding, design tokens, specification)
is applied to real source files in the workspace. Edits are targeted and
verifiable: after writing, the orchestrator rebuilds and re-runs the test
suite, so a bad edit is caught rather than shipped.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from .workspace import WorkspaceError, read_file, write_file


def apply_branding(db, workspace, root: Path, brand: dict) -> list[str]:
    """Rewrite brand identity and document metadata in the generated sources."""
    changed: list[str] = []
    display = brand["brand"]
    short = brand.get("brand_short") or display[:1]
    tagline = brand.get("tagline") or "Considered everyday objects."

    index_path = "frontend/public/index.html"
    try:
        html = read_file(root, index_path)
    except WorkspaceError:
        return changed
    original = html
    html = re.sub(r"<title>.*?</title>", f"<title>{display} — {tagline}</title>", html, count=1, flags=re.S)
    html = re.sub(r'(<meta name="description" content=")[^"]*(")',
                  rf"\g<1>{display} — {tagline}\g<2>", html)
    html = re.sub(r'<span class="brand-mark" aria-hidden="true">[^<]*</span>',
                  f'<span class="brand-mark" aria-hidden="true">{html_escape(short[:1])}</span>', html)
    html = re.sub(r'<span class="brand-text">.*?</span>',
                  f'<span class="brand-text">{html_escape(display)}</span>', html, count=1, flags=re.S)
    html = html.replace("Aurora &amp; Co.", html_escape(display)).replace("Aurora & Co.", html_escape(display))
    if html != original:
        write_file(root, index_path, html, agent_id="design", phase="implementation",
                   is_ai_generated=True, db=db, workspace=workspace)
        changed.append(index_path)

    main_path = "frontend/src/main.js"
    try:
        main_js = read_file(root, main_path)
        updated = main_js.replace("Aurora & Co. — Everyday objects, considered", f"{display} — {tagline}")
        if updated != main_js:
            write_file(root, main_path, updated, agent_id="frontend", phase="implementation",
                       is_ai_generated=True, db=db, workspace=workspace)
            changed.append(main_path)
    except WorkspaceError:
        pass

    package_path = "package.json"
    try:
        package = json.loads(read_file(root, package_path))
        package["name"] = re.sub(r"[^a-z0-9-]+", "-", display.lower()).strip("-") or "nexora-app"
        package["description"] = f"{display} — generated by NEXORA AI LABS"
        write_file(root, package_path, json.dumps(package, indent=2) + "\n",
                   agent_id="devops", phase="implementation", db=db, workspace=workspace)
        changed.append(package_path)
    except (WorkspaceError, ValueError):
        pass

    hero_path = "frontend/src/views/store.js"
    try:
        hero = read_file(root, hero_path)
        original_hero = hero
        first_word = display.split()[0] if display.split() else "Everyday"
        hero = hero.replace(
            "<h1>Everyday objects,<br><em>considered.</em></h1>",
            f"<h1>{html_escape(first_word)} essentials,<br><em>considered.</em></h1>",
        )
        if hero != original_hero:
            write_file(root, hero_path, hero, agent_id="frontend", phase="implementation",
                       is_ai_generated=True, db=db, workspace=workspace)
            changed.append(hero_path)
    except WorkspaceError:
        pass

    return changed


def html_escape(value: str) -> str:
    return (str(value).replace("&", "&amp;").replace("<", "&lt;")
            .replace(">", "&gt;").replace('"', "&quot;"))


def apply_design_tokens(db, workspace, root: Path, design: dict) -> list[str]:
    """Apply the AI designer's palette to the real stylesheet."""
    palette = design.get("palette") or {}
    css_path = "frontend/src/styles.css"
    try:
        css = read_file(root, css_path)
    except WorkspaceError:
        return []
    original = css
    mapping = {
        "--bg": palette.get("background"),
        "--panel": palette.get("surface"),
        "--text": palette.get("text"),
        "--gold": palette.get("accent"),
    }
    applied: list[str] = []
    for token, value in mapping.items():
        if not isinstance(value, str) or not re.match(r"^#[0-9a-fA-F]{3,8}$", value):
            continue
        updated = re.sub(rf"({re.escape(token)}:\s*)#[0-9a-fA-F]{{3,8}};", rf"\g<1>{value};", css, count=1)
        if updated != css:
            css = updated
            applied.append(token)
    if css != original:
        write_file(root, css_path, css, agent_id="design", phase="implementation",
                   is_ai_generated=True, db=db, workspace=workspace)
        return [css_path]
    return []


def write_documentation(db, workspace, root: Path, docs: dict[str, tuple[str, str]]) -> list[str]:
    """Write agent-authored documentation files.

    ``docs`` maps ``relative_path -> (agent_id, content)``.
    """
    written: list[str] = []
    for relative, (agent_id, content) in docs.items():
        write_file(root, relative, content, agent_id=agent_id, phase="documentation",
                   is_ai_generated=True, db=db, workspace=workspace)
        written.append(relative)
    return written
